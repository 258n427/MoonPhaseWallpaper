#==================================================================================================
# logv
#
# Logs a message when verbose or debug mode is enabled.
#==================================================================================================
logv()
{
    if $debug_mode || $verbose_mode; then
        echo "$@"
    fi
    return 0
}

#==================================================================================================
# logd
#
# Logs a message when debug mode is enabled.
#==================================================================================================
logd()
{
    if $debug_mode; then
        echo "$@"
    fi
    return 0
}

